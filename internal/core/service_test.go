func TestAnalyzeRealCore(t *testing.T) {
	cc, err := exec.LookPath("cc")
	if err != nil {
		t.Skip("cc is not installed")
	}
	gdb, err := exec.LookPath("gdb")
	if err != nil {
		t.Skip("gdb is not installed")
	}
	gcore, err := exec.LookPath("gcore")
	if err != nil {
		t.Skip("gcore is not installed")
	}
	root := t.TempDir()
	program := filepath.Join(root, "core-target")
	source := filepath.Join(root, "core-target.c")
	if err := os.WriteFile(source, []byte("#include <sys/prctl.h>\n#include <unistd.h>\nint main(void){ prctl(PR_SET_PTRACER, PR_SET_PTRACER_ANY); for(;;) sleep(1); }\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if output, err := exec.Command(cc, "-g", "-O0", "-o", program, source).CombinedOutput(); err != nil {
		t.Skipf("compile core target: %v\n%s", err, output)
	}
	if err := os.Chmod(program, 0o755); err != nil {
		t.Fatal(err)
	}
	child := exec.Command(program)
	if err := child.Start(); err != nil {
		t.Skipf("start core target: %v", err)
	}
	defer func() {
		if child.Process != nil {
			_ = child.Process.Kill()
		}
		_ = child.Wait()
	}()
	time.Sleep(150 * time.Millisecond)
	prefix := filepath.Join(root, "core")
	if output, err := exec.Command(gcore, "-o", prefix, strconv.Itoa(child.Process.Pid)).CombinedOutput(); err != nil {
		t.Skipf("gcore is restricted in this environment: %v\n%s", err, output)
	}
	cores, err := filepath.Glob(prefix + ".*")
	if err != nil || len(cores) == 0 {
		t.Fatalf("gcore produced no core file: %v %v", cores, err)
	}
	if err := os.Chmod(cores[0], 0o600); err != nil {
		t.Fatal(err)
	}
	store, err := artifacts.NewStore(filepath.Join(t.TempDir(), "reports"), 8<<20)
	if err != nil {
		t.Fatal(err)
	}
	service, err := NewService(ServiceOptions{
		Runner: runner.New(),
		Binary: func() (string, string, error) { return gdb, "gdb", nil },
		Profiles: []config.CoreProfile{{
			ID: "fixture", Executable: program, Core: cores[0],
		}},
		Roots: []string{root}, Store: store,
	})
	if err != nil {
		t.Fatal(err)
	}
	report, err := service.Analyze(context.Background(), Request{ProfileID: "fixture"})
	if err != nil {
		t.Fatalf("Analyze() error = %v", err)
	}
	if !report.Complete || len(report.Threads) == 0 {
		t.Fatalf("report = %+v", report)
	}
	if !strings.Contains(report.Output, "Core was generated") {
		t.Errorf("output does not look like a loaded core: %s", report.Output[:min(len(report.Output), 500)])
	}
	if report.Evidence == nil {
		t.Fatal("core report has no raw evidence reference")
	}
	artifact, err := service.Artifact(context.Background(), ArtifactRequest{
		RunID: report.Evidence.RunID, MaxBytes: 100,
	})
	if err != nil {
		t.Fatalf("Artifact() error = %v", err)
	}
	if artifact.FileName != "core-gdb.log" || artifact.Content == "" {
		t.Errorf("artifact = %+v", artifact)
	}
}

func min(left, right int) int {
	if left < right {
		return left
	}
	return right
}

func TestAnalyzeRejectsUnknownProfileAndBadFiles(t *testing.T) {
	service, err := NewService(ServiceOptions{
		Runner: runner.New(),
		Binary: func() (string, string, error) { return "/usr/bin/gdb", "gdb", nil },
	})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := service.Analyze(context.Background(), Request{ProfileID: "missing"}); CodeOf(err) != CodeProfileUnknown {
		t.Fatalf("unknown profile error = %v", err)
	}
}

type fakeCoreRunner struct {
	result runner.Result
	stdout string
	stderr string
}

func (f fakeCoreRunner) Run(_ context.Context, req runner.Request) (runner.Result, error) {
	if req.Stdout != nil {
		_, _ = req.Stdout.Write([]byte(f.stdout))
	}
	if req.Stderr != nil {
		_, _ = req.Stderr.Write([]byte(f.stderr))
	}
	return f.result, nil
}

func TestCoreDegradedOutputIsIncomplete(t *testing.T) {
	root := t.TempDir()
	executable := filepath.Join(root, "target")
	corePath := filepath.Join(root, "core")
	if err := os.WriteFile(executable, []byte("binary"), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(corePath, []byte("core"), 0o600); err != nil {
		t.Fatal(err)
	}
	service, err := NewService(ServiceOptions{
		Runner: fakeCoreRunner{
			result: runner.Result{Started: true, ExitCode: 0},
			stdout: "Core was generated by target.\nReading symbols from target...\n" +
				"Core file may not match specified executable file.\n" +
				"No debugging symbols found\n* 1 Thread 0x1 (LWP 1)\n",
		},
		Binary:   func() (string, string, error) { return "/usr/bin/gdb", "gdb", nil },
		Profiles: []config.CoreProfile{{ID: "fixture", Executable: executable, Core: corePath}},
		Roots:    []string{root},
	})
	if err != nil {
		t.Fatal(err)
	}
	report, err := service.Analyze(context.Background(), Request{ProfileID: "fixture"})
	if err != nil {
		t.Fatal(err)
	}
	if report.Complete {
		t.Fatalf("degraded core was marked complete: %+v", report)
	}
}

func TestCoreEvidencePreservesFullCollectedOutput(t *testing.T) {
	root := t.TempDir()
	executable := filepath.Join(root, "target")
	corePath := filepath.Join(root, "core")
	if err := os.WriteFile(executable, []byte("binary"), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(corePath, []byte("core"), 0o600); err != nil {
		t.Fatal(err)
	}
	store, err := artifacts.NewStore(filepath.Join(t.TempDir(), "reports"), 8<<20)
	if err != nil {
		t.Fatal(err)
	}
	long := "Core was generated by target.\n* 1 Thread 0x1 (LWP 1)\n" + strings.Repeat("x", MaxReportOutputBytes+100)
	service, err := NewService(ServiceOptions{
		Runner:   fakeCoreRunner{result: runner.Result{Started: true, ExitCode: 0}, stdout: long},
		Binary:   func() (string, string, error) { return "/usr/bin/gdb", "gdb", nil },
		Profiles: []config.CoreProfile{{ID: "fixture", Executable: executable, Core: corePath}},
		Roots:    []string{root}, Store: store,
	})
	if err != nil {
		t.Fatal(err)
	}
	report, err := service.Analyze(context.Background(), Request{ProfileID: "fixture"})
	if err != nil {
		t.Fatal(err)
	}
	if report.Complete || report.Evidence == nil || !report.Evidence.Truncated {
		t.Fatalf("report = %+v", report)
	}
	artifact, err := service.Artifact(context.Background(), ArtifactRequest{
		RunID: report.Evidence.RunID, MaxBytes: 64,
	})
	if err != nil {
		t.Fatal(err)
	}
	if artifact.Bytes <= int64(MaxReportOutputBytes) {
		t.Errorf("evidence bytes = %d, want full collected output", artifact.Bytes)
	}
}
